module Resteze
  # The action routing DSL for resources. Each class stores only its own
  # declarations; resolution walks the chain lazily on every lookup:
  # REST built-ins, module action_defaults, module declarations, ancestor
  # classes (farthest first), then this class.
  module Actions
    extend ActiveSupport::Concern

    module ClassMethods
      def action(name, **options)
        name = name.to_sym
        validate_action_options!(name, options)
        reserved = Resteze::Action::RESERVED.include?(name)
        check_action_collision!(name, options) unless reserved || inherited_action?(name)
        declared_actions[name] = options
        define_action_methods(name, options) unless reserved
        nil
      end

      def declared_actions
        @declared_actions ||= {}
      end

      def actions
        action_names.to_h { |name| [name, resolve_action(name)] }.freeze
      end

      # Override to transform params before an action request is sent.
      def action_params(_name, params)
        params
      end

      # Override to supply headers for an action request.
      def action_headers(_name, _params)
        {}
      end

      def invoke_action(name, params = {}, id: nil)
        action = actions.fetch(name)
        raise_invalid_action_id!(id) if action.member? && id.blank?

        params = action_params(name, params)
        params = { action.id_param => id }.merge(params) if action.member? && action.id == :param
        response = request(action.http_method, action.path_for(id), params:, headers: action_headers(name, params))
        build_action_result(action, response)
      end

      private

      def raise_invalid_action_id!(id)
        raise api_module::InvalidRequestError.new(
          "Could not determine which PATH to request: #{self} instance has invalid ID: #{id.inspect}", "id"
        )
      end

      def build_action_result(_action, response)
        api_module::Result.from_response(response)
      end

      # True when an ancestor class already declared this action, so the method
      # that exists was generated by the DSL and may be overridden.
      def inherited_action?(name)
        action_ancestors.drop(1).any? { |klass| klass.declared_actions.key?(name) }
      end

      def check_action_collision!(name, options)
        method_name = (options[:as] || name).to_sym
        member = declaration_scope(name, options) == :member
        clash = respond_to?(method_name, true) ||
                (member && (method_defined?(method_name) || private_method_defined?(method_name)))
        return unless clash

        raise ArgumentError, "action :#{name} would define #{self}.#{method_name}, which already exists; " \
                             "pass as: to choose another method name"
      end

      def define_action_methods(name, options)
        method_name = (options[:as] || name).to_sym
        if declaration_scope(name, options) == :member
          define_method(method_name) { |**params| self.class.invoke_action(name, params, id:) }
          define_singleton_method(method_name) { |id, **params| new(id).public_send(method_name, **params) }
        else
          define_singleton_method(method_name) { |**params| invoke_action(name, params) }
        end
      end

      def action_names
        (Resteze::Action::RESERVED + action_ancestors.flat_map { |klass| klass.declared_actions.keys }).uniq
      end

      # Classes in the ancestry that hold declarations, nearest first.
      def action_ancestors
        ancestors.select { |ancestor| ancestor.is_a?(Class) && ancestor.respond_to?(:declared_actions) }
      end

      def resolve_action(name)
        options = Resteze::Action::BUILT_IN.fetch(name, {}).merge(api_module.action_defaults)
        options.merge!(api_module.action_declarations.fetch(name, {}))
        action_ancestors.reverse_each { |klass| options.merge!(klass.declared_actions.fetch(name, {})) }
        Resteze::Action.new(name, self, options)
      end

      def validate_action_options!(name, options)
        validate_option_keys!(options)
        validate_reserved_scope!(name, options)
        validate_id_options!(name, options)
        validate_returns!(name, options)
      end

      def validate_option_keys!(options)
        unknown = options.keys - Resteze::Action::OPTIONS
        raise ArgumentError, "Unknown action option(s): #{unknown.join(', ')}" if unknown.any?
      end

      def validate_reserved_scope!(name, options)
        return unless Resteze::Action::RESERVED.include?(name) && options.key?(:on)

        raise ArgumentError, "on: cannot be changed for the built-in action :#{name}"
      end

      def validate_id_options!(name, options)
        return unless declaration_scope(name, options) == :collection
        return unless options.key?(:id) || options.key?(:id_param)

        raise ArgumentError, "id: and id_param: only apply to member actions (action :#{name})"
      end

      def validate_returns!(name, options)
        return unless options[:returns] == :list && !(self <= Resteze::List)

        raise ArgumentError, "returns: :list requires #{self} to include List (action :#{name})"
      end

      def declaration_scope(name, options)
        options[:on] ||
          api_module.action_declarations.dig(name, :on) ||
          Resteze::Action::BUILT_IN.dig(name, :on) ||
          :collection
      end
    end
  end
end
